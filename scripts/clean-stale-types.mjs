// Сносит сгенерированные Next описания типов от ПРОШЛЫХ сборок перед новой.
//
// 11–12.08.2026 из-за них встали деплои: три пуша подряд не доехали до прода, при этом сайт
// был жив и отвечал 200, а прогон падал за 45 секунд — то есть внешне ничего не происходило.
//
// Механизм. Next на каждый маршрут кладёт в <distDir>/types заглушку вида
//
//     // File: /var/www/airportsboard/app/api/airports/nearest/route.ts
//     import * as entry from '../../../../../../app/api/airports/nearest/route.js'
//
// а tsconfig.json подключает эти заглушки к проверке типов. Сборка здесь идёт в
// .next-build (см. distDir в next.config.ts и scripts/swap-build.mjs), поэтому живой каталог
// .next/types НЕ перезаписывается — он остаётся от последней удачной сборки. Деплой его тоже
// не трогает: `git clean -fd` идёт без -x и игнорируемые файлы не удаляет.
//
// Стоило удалить маршрут /api/airports/nearest — и заглушка на него осталась висеть, ссылаясь
// на исходник, которого больше нет:
//
//     Type error: Cannot find module '.../app/api/airports/nearest/route.js'
//
// Дальше это самоподдерживается: падение обрывает цепочку `&&`, swap-build не выполняется,
// .next остаётся старым вместе с мусором — и следующий пуш падает так же. Выйти из этого
// изнутри репозитория было нельзя: чинить надо то, что лежит на сервере.
//
// Почему одной правки tsconfig мало. Список include правит САМ Next: он дописывает туда
// каталог типов всякий раз, когда собирают с новым distDir (я это увидел прямо на пробном
// прогоне — он добавил .next-repro/types/**/*.ts). Значит убранную запись он может вернуть,
// и тогда мина встанет обратно. Здесь же мусора просто не остаётся, чем бы ни кончилась
// правка конфига.
//
// Запускается из npm run build перед next build.

import fs from 'node:fs';

/**
 * .next/types — мина из объяснения выше.
 * .next-build — промежуточный каталог сборки: в нём тоже копятся заглушки на удалённые
 * маршруты, просто до сих пор везло, что он пересоздавался целиком.
 */
const STALE = ['.next/types', '.next-build'];

for (const dir of STALE) {
  if (!fs.existsSync(dir)) continue;
  fs.rmSync(dir, { recursive: true, force: true });
  console.log(`  снесено перед сборкой: ${dir}`);
}
