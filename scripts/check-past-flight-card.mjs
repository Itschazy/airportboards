// Карточка прошедшего рейса: не гонит ли она человека к выходу на рейс, который уже ушёл.
//
// Замер, из-за которого проверка появилась (12.08.2026, девять бортов прода): 91 строка из
// 287 — треть всех открытий карточки — показывала «Выход закроется в 974 мин», «Срочно
// направляйтесь к выходу. После закрытия выхода на посадку не допускают» и завтрашнюю дату.
// А открыть карточку и есть единственное осмысленное действие на странице.
//
// Причина: `minsUntil` считал по СТРОКЕ времени («05:05») и докручивал сутки —
// `if (diff < -300) diff += 1440`, — то есть всё старше пяти часов объявлялось завтрашним.
// Рейс в 05:05 при местных 12:51 давал −466 → 974 минуты «до посадки».
//
// Само по себе «прошедший рейс со статусом посадка» — не ошибка данных: статус строится от
// часов СНИМКА (mapStatus в lib/flights.ts), а снимку бывает шесть часов. Писать из-за этого
// «Вылетел» нельзя — вылета снимок не видел. Нельзя другое: считать обратный отсчёт и
// побуждать к действию.
//
// Проверяются ДВЕ вещи:
//   1. причина в коде — расчёт берёт отметку времени, а все побуждающие ветки закрыты
//      признаком «уже прошло». Это ловит регрессию без выкатки;
//   2. цена на живых данных — сколько строк прода прямо сейчас попало бы под старую
//      докрутку. Печатается как контекст: сама по себе она провалом не считается, потому
//      что зависит от свежести прогрева, а не от кода.
//
// Провайдерские эндпоинты не трогаются: страницы читаются обычным GET с не-браузерным UA.
//
// Usage:  node scripts/check-past-flight-card.mjs [base]

import fs from 'node:fs';

const BASE = process.argv[2] || 'http://localhost:3002';
const CODES = (process.argv[3] || 'SVO,AYT,DXB,IST,KZN,LED,HND,SIN,DEL,JFK').split(',');

const SRC = fs.readFileSync('components/FlightBoard.tsx', 'utf8');

let fails = 0;
const say = (ok, msg) => { if (!ok) fails++; console.log(`  ${ok ? '✓' : '✗'} ${msg}`); };

// ── 1. Причина в коде ─────────────────────────────────────────────────────────────────────

console.log('карточка прошедшего рейса — устройство\n');

say(/minsUntil\s*=\s*\([^)]*\bts\b[^)]*\)/.test(SRC),
  'расчёт принимает отметку времени, а не только строку часов');

say(/if \(ts\) return Math\.round\(\(ts \* 1000 - Date\.now\(\)\)/.test(SRC),
  'при наличии отметки времени арифметика на строках не используется');

say(/const past = mins != null && mins < 0/.test(SRC),
  'признак «время уже прошло» объявлен');

for (const [branch, label] of [
  ["status === 'boarding' && !past", 'посадка'],
  ["status === 'finalcall' && !past", 'последний вызов'],
]) {
  say(SRC.includes(branch), `ветка «${label}» закрыта признаком прошедшего времени`);
}

say(/const notice = past \? null :/.test(SRC),
  'советы «приезжайте заранее» и «срочно к выходу» сняты у прошедшего рейса');

// Обратный отсчёт «Вылет через …» не должен доставаться прошедшему рейсу.
say(/hero = past\s*$|hero = past\s/.test(SRC) || SRC.includes('hero = past'),
  'обратный отсчёт заменён нейтральной карточкой');

// ── 2. Цена на живых данных ───────────────────────────────────────────────────────────────

console.log(`\nсколько строк прода попало бы под старую докрутку (${BASE})\n`);

/** Старая формула — ровно та, что стояла в коде, для оценки масштаба. */
const oldMins = (hhmm, nowH, nowM) => {
  const [h, m] = hhmm.split(':').map(Number);
  let d = (h * 60 + m) - (nowH * 60 + nowM);
  if (d < -300) d += 1440;
  return d;
};

let rows = 0, wrapped = 0, boards = 0;

for (const code of CODES) {
  let html;
  try {
    const res = await fetch(`${BASE}/ru/airport/${code}`, { headers: { 'user-agent': 'audit-bot' } });
    if (!res.ok) { console.log(`  ${code.padEnd(5)} HTTP ${res.status}`); continue; }
    html = await res.text();
  } catch (e) { console.log(`  ${code.padEnd(5)} не ответил: ${e.message}`); continue; }

  const ts = [...html.matchAll(/\\"ts\\":(\d{9,11})/g)].map((m) => Number(m[1]));
  const times = [...html.matchAll(/\\"scheduled\\":\\"([0-2]\d:[0-5]\d)\\"/g)].map((m) => m[1]);
  if (!ts.length) { console.log(`  ${code.padEnd(5)} борт не прогрет`); continue; }

  boards++;
  const now = Date.now() / 1000;
  let past = 0, wrap = 0;
  for (let i = 0; i < ts.length; i++) {
    rows++;
    if (ts[i] >= now) continue;
    past++;
    // Как далеко в прошлом: старая формула докручивала всё, что дальше пяти часов.
    if ((now - ts[i]) / 60 > 300 && times[i]) { wrap++; wrapped++; }
  }
  console.log(`  ${code.padEnd(5)} строк ${String(ts.length).padStart(3)}, в прошлом ${String(past).padStart(3)}, докрутилось бы ${String(wrap).padStart(3)}`);
}

console.log(`\nизмерено бортов: ${boards}, строк ${rows}; под докрутку попало бы ${wrapped}`
  + (rows ? ` (${(100 * wrapped / rows).toFixed(1)}%)` : ''));
console.log(fails
  ? `\nПРОВАЛОВ: ${fails} — карточка снова может гнать к выходу на ушедший рейс`
  : '\nу прошедшего рейса карточка нейтральна: без отсчёта, без побуждений, без завтрашней даты');

process.exit(fails ? 1 : 0);
