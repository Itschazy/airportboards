// Закрыты ли денежные ручки — и закрыты ли они тем способом, который действительно работает.
//
// Заведён 31.10.2026 по аудиту, который нашёл /api/cron/warm открытым всему интернету. Дефект
// прожил долго, и причина ровно та же, что у трёх других сторожей этого репозитория: снаружи
// он не проявляется НИКАК. Ручка отвечает 200, страницы целые, проверки зелёные — просто тик
// прогрева может запустить кто угодно, а тик берёт до половины дневной доли платного плана.
//
// Что именно было:
//
//   1. isCronRequest = hasToken(req) || isLoopbackHost(req). Второе слагаемое задумано как
//      «запрос с самой машины», но за nginx петлевой Host приходит у КАЖДОГО запроса из
//      интернета: next start строит nextUrl из адреса, на котором слушает сам. Это уже было
//      измерено дважды — на /api/airlabs-usage 19.07 и на живой покупке 18.10 (refused.localhost
//      на каждого читателя, см. lib/live-budget.ts), — и /api/revalidate поэтому с самого
//      начала стоит на строгой проверке. Прогрев остался на слабой.
//   2. Минимальный интервал между тиками жил в переменной модуля (let lastRunAt), а процессов
//      с 18.10 три: у каждого свой счёт, заслон втрое слабее заявленного.
//   3. runsPerDay принимался от любого вызывающего, а он делит дневную долю: чем меньше
//      число, тем больше достаётся одному тику.
//   4. /api/flights не проверял код аэропорта по каталогу, хотя direction рядом проверяется
//      ровно от этой угрозы: неизвестный ключ хранилища пуст всегда, значит каждый запрос
//      уходит к поставщику за деньги — и вдобавок без отметки времени, то есть по
//      привилегированному пути freshnessOverride, сверх людской доли плана.
//
// Проверка смотрит в исходник, а не в живой сайт: ручку прогрева запрашивать нельзя — она
// покупает данные. Поведение решающих функций закрыто отдельно, утверждениями в коде.
import fs from 'node:fs';

let fails = 0;
const say = (ok, msg) => { if (!ok) fails++; console.log(`  ${ok ? '✓' : '✗'} ${msg}`); };
/** Исходник без комментариев: разбор дефекта в комментарии не должен считаться дефектом. */
const code = (p) => fs.readFileSync(p, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

const AUTH = code('lib/api-auth.ts');
const WARM = code('app/api/cron/warm/route.ts');
const FLIGHTS = code('app/api/flights/[iata]/route.ts');

console.log('Денежные ручки:');

// ── 1. Слабая проверка не вернулась ──────────────────────────────────────────────────────
say(!/hasToken\(req\)\s*\|\|\s*isLoopbackHost\(req\)/.test(AUTH),
  !/hasToken\(req\)\s*\|\|\s*isLoopbackHost\(req\)/.test(AUTH)
    ? 'слабого правила «токен ИЛИ петля» в lib/api-auth.ts нет'
    : 'ВЕРНУЛОСЬ «токен ИЛИ петля»: за nginx петля — это весь интернет');
say(!/isCronRequest/.test(AUTH + WARM),
  !/isCronRequest/.test(AUTH + WARM) ? 'isCronRequest не используется' : 'isCronRequest снова в деле');

// ── 2. Вход в прогрев — через вердикт, и отказ действительно отказывает ──────────────────
say(/warmerVerdict\(req\)/.test(WARM) && /status:\s*403/.test(WARM),
  /warmerVerdict\(req\)/.test(WARM) && /status:\s*403/.test(WARM)
    ? 'прогрев спрашивает warmerVerdict и отдаёт 403 неизвестному'
    : 'прогрев не проверяет вызывающего или не отказывает ему');
// Вердикт обязан держаться на ПРЕДЪЯВЛЕННОМ токене, а не на виде запроса: «петлевой» вход
// недостижим — Next дописывает x-forwarded-* каждому запросу (разбор у cameThroughProxy).
say(/export function warmerVerdict[\s\S]{0,400}?hasToken\(req\)/.test(AUTH),
  /export function warmerVerdict[\s\S]{0,400}?hasToken\(req\)/.test(AUTH)
    ? 'вердикт держится на предъявленном токене'
    : 'вердикт прогрева больше не требует токена');
// Единственное послабление — ненастроенный CRON_TOKEN: иначе крон встал бы молча. Оно
// обязано остаться видимым, иначе это просто дыра.
say(/cronTokenConfigured\(\)/.test(AUTH) && /unconfigured/.test(WARM) && /console\.error/.test(WARM),
  /cronTokenConfigured\(\)/.test(AUTH) && /unconfigured/.test(WARM) && /console\.error/.test(WARM)
    ? 'ненастроенный токен оставляет прогрев живым, но кричит в лог'
    : 'послабление при ненастроенном токене стало молчаливым');

// ── 3. Интервал между тиками — один на все процессы ──────────────────────────────────────
say(/claimWarmTick\(/.test(WARM) && !/let lastRunAt/.test(WARM),
  /claimWarmTick\(/.test(WARM) && !/let lastRunAt/.test(WARM)
    ? 'интервал между тиками общий для всех процессов'
    : 'интервал между тиками снова в памяти процесса — втроём они пропустят втрое больше');

// ── 4. Расписание задаёт только тот, у кого токен ─────────────────────────────────────────
say(/runsPerDay\s*=\s*operator\s*&&/.test(WARM),
  /runsPerDay\s*=\s*operator\s*&&/.test(WARM)
    ? 'runsPerDay принимается только по токену'
    : 'runsPerDay принимается от любого вызывающего — дневную долю можно отдать одному тику');

// ── 5. Борт покупается только для аэропорта из каталога ──────────────────────────────────
const checksCatalogue = /getAirport\(code\)/.test(FLIGHTS)
  && FLIGHTS.indexOf('getAirport(code)') < FLIGHTS.indexOf('getBoard(code');
say(checksCatalogue,
  checksCatalogue
    ? 'ручка /api/flights проверяет код по каталогу ДО покупки'
    : 'ручка /api/flights покупает борт для любой строки — мусорный код платный и привилегированный');

// ── 6. Число процессов берётся не из догадки об имени переменной ─────────────────────────
const BUDGET = code('lib/live-budget.ts');
say(/WEB_INSTANCES/.test(BUDGET) && /instanceInfo/.test(BUDGET) && /instanceInfo\(\)/.test(code('app/api/health/route.ts')),
  /WEB_INSTANCES/.test(BUDGET) && /instanceInfo/.test(BUDGET) && /instanceInfo\(\)/.test(code('app/api/health/route.ts'))
    ? 'число процессов приходит явно и видно в /api/health'
    : 'число процессов снова непроверяемо — ошибка в имени переменной утроит потолок молча');

console.log(fails ? `\nПРОВАЛОВ: ${fails}` : '\nденьги тратят только те, кому можно');
process.exit(fails ? 1 : 0);
