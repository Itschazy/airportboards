// Попадает ли прогрев в собственный юбилейный тик.
//
// Дефект, из-за которого проверка появилась, не виден ни в логах, ни на странице — он виден
// только в арифметике. Отбор шёл так:
//
//     const overdue = (now - ts) / (interval * 60_000);
//     if (overdue < 1) continue;
//
// Тик стартует в HH:00:03, а прошлая запись легла в HH:00:0x…HH:00:16: `put()` пишется ПОСЛЕ
// ответа поставщика, со сдвигом 120 мс на аэропорт. Значит на юбилейном тике возраст на
// секунды МЕНЬШЕ интервала, и аэропорт выбрасывался:
//
//     KZN прогрет 00:00:10 → тик 06:00:03  overdue = 0.99964  → выброшен
//     IST прогрет 00:00:07 → тик 06:00:03  overdue = 0.99977  → выброшен
//     ORD прогрет 20:00:06 → тик 02:00:03  overdue = 0.99986  → выброшен
//
// Тики идут раз в два часа, поэтому промах стоил ровно два лишних часа КАЖДОМУ ярусу: цель
// 6 ч превращалась в 8, 12 в 14, 24 в 26. Под это попадал любой аэропорт, записанный позже
// первых двух секунд тика, то есть практически весь корпус.
//
// Проверяется поведение, а не текст: берутся реальные интервалы ярусов из lib/warm.ts и
// прогоняются через ту же арифметику при типичных сдвигах записи.
//
// Usage:  node scripts/check-warm-tick.mjs

import fs from 'node:fs';

const SRC = fs.readFileSync('lib/warm.ts', 'utf8');

let fails = 0;
const say = (ok, msg) => { if (!ok) fails++; console.log(`  ${ok ? '✓' : '✗'} ${msg}`); };

console.log('прогрев попадает в свой тик\n');

// ── 1. Допуск объявлен и участвует в отборе ───────────────────────────────────────────────

const lagMatch = SRC.match(/const TICK_LAG_MS = (\d+) \* 60_000/);
const LAG_MIN = lagMatch ? Number(lagMatch[1]) : 0;

say(!!lagMatch, lagMatch ? `допуск на отставание записи объявлен: ${LAG_MIN} мин` : 'допуска на отставание записи НЕТ');
say(/if \(age \+ TICK_LAG_MS < interval \* 60_000\) continue/.test(SRC),
  'отбор учитывает допуск, а не сравнивает голое отношение с единицей');
say(!/if \(overdue < 1\) continue/.test(SRC),
  'старое сравнение `overdue < 1` убрано');

// ── 2. Поведение на реальных интервалах ───────────────────────────────────────────────────

/** Интервалы ярусов берутся из самого файла, чтобы проверка не разъехалась с кодом. */
const intervals = [...SRC.matchAll(/intervalMin:\s*(\d+)/g)].map((m) => Number(m[1]));
const uniq = [...new Set(intervals)].sort((a, b) => a - b);

console.log(`\nинтервалы ярусов: ${uniq.join(', ')} мин`);
console.log(`\n${'интервал'.padEnd(10)}${'сдвиг записи'.padStart(14)}${'взят на юбилейном тике'.padStart(26)}`);

/**
 * Типичные сдвиги: запись ложится через секунды после старта тика. Триста аэропортов по
 * 120 мс — это 36 секунд, дальше идёт время ответа поставщика; минуту берём с запасом.
 */
const LAGS_SEC = [3, 7, 16, 36, 60];
const TICK_START_LAG_SEC = 3;      // сам тик стартует не ровно в HH:00:00

for (const interval of uniq) {
  for (const lag of LAGS_SEC) {
    // Возраст на юбилейном тике: интервал минус (сдвиг записи − сдвиг старта тика).
    const age = interval * 60_000 - (lag - TICK_START_LAG_SEC) * 1000;
    const due = age + LAG_MIN * 60_000 >= interval * 60_000;
    if (!due) fails++;
    console.log(`  ${String(interval).padEnd(8)}${(lag + ' с').padStart(14)}${(due ? 'да' : 'НЕТ — уедет на лишний тик').padStart(26)}`);
  }
}

// ── 3. Допуск не должен вызывать двойной прогрев ──────────────────────────────────────────

/** Тик идёт раз в два часа (см. crontab на сервере и MIN_INTERVAL_MS в маршруте крона). */
const TICK_SPACING_MIN = 120;
const shortest = uniq[0] ?? 0;
say(LAG_MIN < shortest && LAG_MIN < TICK_SPACING_MIN,
  `допуск ${LAG_MIN} мин меньше и кратчайшего интервала (${shortest} мин), и шага тика (${TICK_SPACING_MIN} мин) — двойного прогрева вызвать не может`);

console.log(fails
  ? `\nПРОВАЛОВ: ${fails} — прогрев промахивается мимо своего тика и уезжает на лишний период`
  : '\nпрогрев попадает в свой тик при любом реальном сдвиге записи');
process.exit(fails ? 1 : 0);
