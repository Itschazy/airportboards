// Ежемесячный пересбор data/airport-service.json — САМ, ДВУМЯ ПРОХОДАМИ.
//
// ЗАЧЕМ. Файл отвечает на вопрос «сколько рейсов в сутки у этого кода», и от ответа зависит
// почти всё: ярус прогрева, попадание страницы в карту сайта, заявление подстраницы прилётов,
// текст описания и FAQ. Собирался он вручную, стоил 6 069 обращений и поэтому забывался.
// 04.09.2026 это подвело ДВАЖДЫ за один день:
//
//   · сезонный дрейф — 188 кодов числились обслуживаемыми, хотя рейсов там больше нет;
//   · переезд кодов IATA — Палм-Бич и Манас числились МЁРТВЫМИ, хотя работают под новыми
//     кодами, и страницы печатали читателю прямое отрицание.
//
// Оба дефекта невидимы снаружи: ответ 200, страница целая, все проверки зелёные.
//
// ДВА ПРОХОДА ОБЯЗАТЕЛЬНЫ, И В РАЗНОЕ ВРЕМЯ СУТОК. Поставщик отдаёт скользящее окно примерно
// в 13 часов, а не сутки. Код, чей трафик приходится на другую половину суток, в одном проходе
// выглядит мёртвым. Замер 04.09: из 483 нулей первого прохода при переспросе ожили 295 — то
// есть ОДИН проход даёт 61% ложных нулей. Принимать первый ноль нельзя.
//
// КАК ЭТО РАБОТАЕТ БЕЗ ПАМЯТИ О ПРОШЛОМ ЗАПУСКЕ. Скрипт не хранит расписание — он читает
// состояние из тех же файлов, которыми пользуется сайт, и сам решает, что сейчас уместно:
//
//   очередь переспроса не пуста и старше MIN_GAP_H  →  ВТОРОЙ проход + сверка
//   замер старше MAX_AGE_DAYS и очередь пуста       →  ПЕРВЫЙ проход
//   иначе                                            →  ничего, выход 0
//
// Поэтому его можно звать хоть дважды в день: почти всегда он не делает ничего. Дважды в день
// он и зовётся — иначе второй проход попал бы в тот же час, что первый, и лечил бы ложные нули
// тем же самым окном поставщика.
//
// ЦЕНА: 6 069 + около 500 на переспрос ≈ 6 600 запросов в месяц, 0.66% плана.
//
// Usage:  node scripts/service-remeasure.mjs [--dry]
// Exit:   0 — сделано или делать нечего; 1 — проход упал

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const DRY = process.argv.includes('--dry');
/** Через сколько суток замер считается устаревшим. Расписания сезонные, месяц — разумный шаг. */
const MAX_AGE_DAYS = 28;
/** Минимальный разрыв между проходами. Меньше — и второй проход попадёт в то же окно поставщика. */
const MIN_GAP_H = 6;

const SERVICE = 'data/airport-service.json';
const QUEUE = 'data/airport-service-recheck.json';
/**
 * Свежий проход пишется СЮДА, а не в SERVICE (исправлено 25.10.2026).
 *
 * Прежняя редакция звала discover-schedules.mjs без --refresh и без --out. Без --refresh он
 * пропускает всё уже известное — то есть первый проход не спрашивал поставщика НИ О ЧЁМ
 * (прогон 25.10 06:13: «to probe 0»), и замер стоял с 04.09. Но и одного --refresh было бы мало:
 * тогда проход переписал бы рабочий файл сайта на месте, вместе с первыми нулями, а очередь
 * переспроса не завелась бы вовсе (её пишет только reconcile-service.mjs) — то есть второй проход
 * не наступил бы никогда, и 61% ложных нулей уходили бы прямо на страницы.
 *
 * Теперь оба прохода пишут во временный файл, а reconcile-service.mjs сравнивает его с рабочим:
 * положительные счета принимает, первый ноль там, где раньше были рейсы, НЕ принимает и кладёт
 * в очередь, второй ноль по той же очереди — принимает.
 */
const FRESH = path.join(os.tmpdir(), 'airport-service-fresh.json');

const read = (p) => { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return null; } };

/**
 * Отметки в этих файлах пишутся в UTC, но БЕЗ буквы Z: reconcile-service.mjs кладёт
 * `new Date().toISOString().slice(0, 16)` — «2026-08-31T20:24».
 *
 * Date.parse по спецификации читает такую строку как МЕСТНОЕ время. На этой машине (UTC+5)
 * очередь возрастом два часа выходила девятичасовой, то есть проходила порог в шесть часов —
 * и второй проход шёл почти в то же окно поставщика, ради разрыва с которым он и существует.
 * Поймано собственным прогоном по веткам: ветка «очередь ждёт» не сработала ни разу.
 *
 * Дату без времени («2026-09-04») спецификация читает как UTC — там расхождения нет.
 */
const parseUtc = (s) => Date.parse(/T\d\d:\d\d/.test(s) && !/(Z|[+-]\d\d:?\d\d)$/.test(s) ? `${s}Z` : s);
const run = (args) => {
  console.log(`  $ node ${args.join(' ')}`);
  if (DRY) return;
  execFileSync('node', args, { stdio: 'inherit' });
};

/** Каждый проход начинает с чистого временного файла: иначе --only дописал бы к прошлому проходу. */
const fresh = () => { if (!DRY) fs.rmSync(FRESH, { force: true }); };

const svc = read(SERVICE);
if (!svc) { console.error(`не читается ${SERVICE} — пересбор пропущен`); process.exit(1); }

const queue = read(QUEUE);
const pending = queue?.codes?.length ?? 0;
// `generated` у очереди — с точностью до минуты (2026-08-31T20:24), у замера — до суток.
const queueAgeH = queue?.generated ? (Date.now() - parseUtc(queue.generated)) / 3600_000 : null;
const svcAgeD = svc.generated ? (Date.now() - parseUtc(svc.generated)) / 86_400_000 : Infinity;

console.log('пересбор замера обслуживания');
console.log(`  замер от ${svc.generated ?? '?'} — возраст ${svcAgeD === Infinity ? '?' : svcAgeD.toFixed(0)} дн (порог ${MAX_AGE_DAYS})`);
console.log(`  очередь переспроса: ${pending} кодов${queueAgeH != null ? `, заведена ${queueAgeH.toFixed(1)} ч назад` : ''}`);

if (pending > 0 && queueAgeH != null && queueAgeH >= MIN_GAP_H) {
  console.log(`\nВТОРОЙ ПРОХОД: ${pending} кодов в другое время суток\n`);
  fresh();
  run(['scripts/discover-schedules.mjs', '--only', QUEUE, '--out', FRESH]);
  run(['scripts/reconcile-service.mjs', FRESH, SERVICE]);
  // Сверка обязана идти СРАЗУ за приёмкой: она снимает наши отрицания там, где OurAirports
  // знает рейсы. Без неё свежие нули публикуются как «регулярных рейсов нет» — ровно то, что
  // 04.09 случилось с Палм-Бичем, Кишинёвом и Манасом.
  run(['scripts/crosscheck-service.mjs']);
  run(['scripts/check-code-moves.mjs']);
  console.log('\nвторой проход завершён — данные готовы к коммиту');
  process.exit(0);
}

if (pending > 0) {
  console.log(`\nничего не делаю: очередь ждёт другого времени суток (нужен разрыв ${MIN_GAP_H} ч)`);
  process.exit(0);
}

if (svcAgeD >= MAX_AGE_DAYS) {
  console.log('\nПЕРВЫЙ ПРОХОД: полный обход корпуса, 6 069 обращений\n');
  fresh();
  run(['scripts/discover-schedules.mjs', '--refresh', '--out', FRESH]);
  run(['scripts/reconcile-service.mjs', FRESH, SERVICE]);
  console.log('\nпервый проход завершён — нули ушли в очередь, второй проход будет следующим запуском');
  process.exit(0);
}

console.log('\nничего не делаю: замер свежий, очередь пуста');
process.exit(0);
