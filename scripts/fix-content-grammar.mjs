// Чинит грамматику в локализованных описаниях аэропортов — закрытыми правилами, не моделью.
//
// data/airport-content/*.json — единственный связный авторский абзац на странице аэропорта,
// и в двух языках он сломан механически и одинаково от файла к файлу:
//
//   РУССКИЙ. «Табло» — средний род и не склоняется, а согласование пришло женское:
//   «на странице доступна онлайн-табло», «вы найдёте актуальную онлайн-табло». Плюс предлог
//   с винительным там, где нужен предложный: «с информацией по прилёты и вылеты».
//
//   КОРЕЙСКИЙ. Слово продублировано подряд: «온라인 온라인» в 2021 файле, «출발 출발» в 80,
//   «도착 도착» в 64. Плюс английское слово внутри корейской фразы — «arrival(도착)과 출발
//   시간» — и калька «플라이트 보드» там, где в корейских аэропортах говорят «운항정보».
//
// Что НЕ трогается и почему:
//   - «на онлайн-табло», «за онлайн-табло», «включая онлайн-табло» — это предлоги, а не
//     согласование, и они верны. Первая версия правила ловила их заодно: 393 ложных
//     срабатывания против 255 настоящих;
//   - удвоение в именах собственных: «Walla Walla», «Pago Pago», «Divi Divi», «다그 다그».
//     Правило работает по списку известных слов, а не по маске «слово повторилось»;
//   - «актуальные онлайн-табло» во множественном числе — грамматически возможно, решает
//     человек; такие случаи только пересчитываются.
//   - буква «ё» сохраняется как в исходном тексте: файл, писавший «прилеты», получит
//     «о прилетах», а писавший «прилёты» — «о прилётах». Иначе внутри одного абзаца
//     появится разнобой.
//
// Usage:
//   node scripts/fix-content-grammar.mjs            — сухой прогон
//   node scripts/fix-content-grammar.mjs --write    — применить

import fs from 'node:fs';
import path from 'node:path';

const WRITE = process.argv.includes('--write');
const DIR = 'data/airport-content';

/**
 * Границы слова заданы явно, а не через `\b`.
 *
 * `\b` в JavaScript определена через `\w`, то есть [A-Za-z0-9_] — в кириллическом тексте
 * границы слова нет вообще, и `/\bдоступна/` не совпадает НИКОГДА. Первая версия этих правил
 * отработала «0 исправлений» на 255 реальных вхождениях и выглядела как успех.
 */
const L = '\\p{L}';
const w = (s) => new RegExp(`(?<![${L}])${s}(?![${L}])`, 'gu');

/** [регэксп, замена, что это] — только закрытые, проверяемые правила. */
const RULES = {
  ru: [
    // Согласование с «табло» (ср. р.). Слово идёт перед «онлайн-табло» или «онлайн табло».
    [w('доступна(\\s+онлайн[- ]табло)'), 'доступно$1', 'доступна → доступно'],
    [w('представлена(\\s+онлайн[- ]табло)'), 'представлено$1', 'представлена → представлено'],
    [w('актуальную(\\s+онлайн[- ]табло)'), 'актуальное$1', 'актуальную → актуальное'],
    [w('актуальная(\\s+онлайн[- ]табло)'), 'актуальное$1', 'актуальная → актуальное'],
    [w('удобную(\\s+онлайн[- ]табло)'), 'удобное$1', 'удобную → удобное'],
    [w('полную(\\s+онлайн[- ]табло)'), 'полное$1', 'полную → полное'],
    [w('подробную(\\s+онлайн[- ]табло)'), 'подробное$1', 'подробную → подробное'],
    [w('доступен(\\s+онлайн[- ]табло)'), 'доступно$1', 'доступен → доступно'],
    // Предлог: «по прилёты и вылеты» → «о прилётах и вылетах». Буква ё — как в оригинале.
    [w('по\\s+прилёты\\s+и\\s+вылеты'), 'о прилётах и вылетах', 'по прилёты → о прилётах'],
    [w('по\\s+прилеты\\s+и\\s+вылеты'), 'о прилетах и вылетах', 'по прилеты → о прилетах'],
    [w('о\\s+прилёты\\s+и\\s+вылеты'), 'о прилётах и вылетах', 'о прилёты → о прилётах'],
    [w('о\\s+прилеты\\s+и\\s+вылеты'), 'о прилетах и вылетах', 'о прилеты → о прилетах'],
    // Род при «табло» в единственном числе — всегда средний, других вариантов нет.
    [w('представлен(\\s+онлайн[- ]табло)'), 'представлено$1', 'представлен → представлено'],
    [w('полезна(\\s+онлайн[- ]табло)'), 'полезно$1', 'полезна → полезно'],
    // МНОЖЕСТВЕННОЕ число здесь НЕ трогается: «доступны онлайн-табло, сведения и контакты» —
    // перечисление, и «доступны» там верно. Отличить его от «доступны онлайн-табло рейсов»
    // закрытым правилом нельзя, поэтому 396 «доступны» и 146 «представлены» остаются человеку.

    // Падеж при «прилёты и вылеты». Форма винительного стоит там, где нужен родительный
    // (после отглагольного существительного) или творительный (после согласуемого слова).
    // Совпадение проверяется ПО СЛОВУ СЛЕВА, потому что сама пара «прилёты и вылеты» бывает
    // и правильной: «проверить прилёты и вылеты» — винительный на месте, 48 таких, и первая
    // версия правила испортила бы их все.
    ...['проверки', 'просмотра', 'контроля', 'мониторинга', 'отслеживания', 'статуса',
      'обновления', 'уточнения', 'разделами', 'секциями']
      .flatMap((head) => [
        [w(`${head}\\s+прилёты\\s+и\\s+вылеты`), `${head} прилётов и вылетов`, `${head} + род. падеж`],
        [w(`${head}\\s+прилеты\\s+и\\s+вылеты`), `${head} прилетов и вылетов`, `${head} + род. падеж (без ё)`],
      ]),
    ...['актуальными', 'текущими', 'свежими', 'последними'].flatMap((head) => [
      [w(`${head}\\s+прилёты\\s+и\\s+вылеты`), `${head} прилётами и вылетами`, `${head} + твор. падеж`],
      [w(`${head}\\s+прилеты\\s+и\\s+вылеты`), `${head} прилетами и вылетами`, `${head} + твор. падеж (без ё)`],
    ]),
    ...['актуальных', 'текущих', 'последних'].flatMap((head) => [
      [w(`${head}\\s+прилёты\\s+и\\s+вылеты`), `${head} прилётов и вылетов`, `${head} + род. падеж`],
      [w(`${head}\\s+прилеты\\s+и\\s+вылеты`), `${head} прилетов и вылетов`, `${head} + род. падеж (без ё)`],
    ]),
    // Предлоги, требующие родительного или предложного.
    [w('для\\s+прилёты\\s+и\\s+вылеты'), 'для прилётов и вылетов', 'для + род. падеж'],
    [w('для\\s+прилеты\\s+и\\s+вылеты'), 'для прилетов и вылетов', 'для + род. падеж (без ё)'],
    [w('об\\s+прилёты\\s+и\\s+вылеты'), 'о прилётах и вылетах', 'об + предл. падеж'],
    [w('об\\s+прилеты\\s+и\\s+вылеты'), 'о прилетах и вылетах', 'об + предл. падеж (без ё)'],
    // «разделы прилёты и вылеты» — название раздела приложено к слову без согласования.
    // Ставим родительный, а не кавычки: кавычки внутри и без того длинной фразы читаются хуже.
    [w('разделы\\s+прилёты\\s+и\\s+вылеты'), 'разделы прилётов и вылетов', 'разделы + род. падеж'],
    [w('разделы\\s+прилеты\\s+и\\s+вылеты'), 'разделы прилетов и вылетов', 'разделы + род. падеж (без ё)'],
    [w('секции\\s+прилёты\\s+и\\s+вылеты'), 'секции прилётов и вылетов', 'секции + род. падеж'],
    [w('секции\\s+прилеты\\s+и\\s+вылеты'), 'секции прилетов и вылетов', 'секции + род. падеж (без ё)'],
    // Прочее удвоение, по конкретным словам.
    [w('погодные\\s+погодные'), 'погодные', 'погодные ×2'],
  ],
  ko: [
    // Удвоение — перечислены именно те слова, что дублируются; имена собственные не трогаем.
    [/온라인\s+온라인/g, '온라인', '온라인 ×2'],
    [/출발\s+출발/g, '출발', '출발 ×2'],
    [/도착\s+도착/g, '도착', '도착 ×2'],
    [/전용\s+전용/g, '전용', '전용 ×2'],
    [/노르웨이\s+노르웨이/g, '노르웨이', '노르웨이 ×2'],
    // Английское слово с корейской глоссой внутри корейской фразы — оставляем корейское.
    [/\b[Aa]rrival\(도착\)/g, '도착', 'arrival(도착) → 도착'],
    [/\b[Dd]eparture\(출발\)/g, '출발', 'departure(출발) → 출발'],
    // Калька вместо принятого в корейских аэропортах слова.
    [/플라이트\s+보드/g, '운항정보', '플라이트 보드 → 운항정보'],
  ],
};

const hits = {};
const touched = new Set();
let files = 0;

for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith('.json'))) {
  const p = path.join(DIR, file);
  const data = JSON.parse(fs.readFileSync(p, 'utf8'));
  let changed = false;
  files++;

  for (const [locale, rules] of Object.entries(RULES)) {
    const text = data[locale];
    if (typeof text !== 'string' || !text) continue;
    let next = text;
    for (const [re, to, label] of rules) {
      const n = (next.match(re) ?? []).length;
      if (!n) continue;
      hits[`${locale}: ${label}`] = (hits[`${locale}: ${label}`] ?? 0) + n;
      next = next.replace(re, to);
    }
    if (next !== text) { data[locale] = next; changed = true; touched.add(file); }
  }

  // Повторный проход: «온라인 온라인 온라인» схлопывается за два шага, а не за один.
  if (changed) {
    for (const [locale, rules] of Object.entries(RULES)) {
      if (typeof data[locale] !== 'string') continue;
      for (const [re, to] of rules) data[locale] = data[locale].replace(re, to);
    }
    if (WRITE) fs.writeFileSync(p, JSON.stringify(data, null, 2) + '\n');
  }
}

const total = Object.values(hits).reduce((a, b) => a + b, 0);
console.log(`${WRITE ? 'исправлено' : 'будет исправлено'}: ${total} вхождений в ${touched.size} файлах из ${files}\n`);
for (const [label, n] of Object.entries(hits).sort((a, b) => b[1] - a[1])) {
  console.log(`  ${String(n).padStart(5)}  ${label}`);
}

// Что осталось за пределами закрытых правил — только пересчёт, решение за человеком.
{
  let plural = 0;
  for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith('.json'))) {
    const ru = JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8')).ru;
    if (typeof ru === 'string' && /\bактуальные\s+онлайн[- ]табло/.test(ru)) plural++;
  }
  if (plural) console.log(`\n  не тронуто: «актуальные онлайн-табло» во множественном числе — ${plural} файлов, решает человек`);
}

// В сухом прогоне это ПРОВЕРКА: ненулевой код возврата, пока в корпусе остаются дефекты.
// Иначе правка живёт ровно до следующей перегенерации описаний и возвращается молча.
if (!WRITE) {
  console.log(total
    ? '\nСухой прогон — ничего не записано. Применить: node scripts/fix-content-grammar.mjs --write'
    : '\nграмматических дефектов в описаниях нет');
  process.exit(total ? 1 : 0);
}
