// Runtime остаётся отдельным от React/Next: один ESM вместо цепочки 10 запросов
// на Slow 4G. Экспорт ленивый, отдельным файлом; старые версии не перезаписываем.
// Используем webpack из закреплённого Next, без нового npm-пакета. После правок:
// node scripts/build-flight-map-runtime.mjs; для CI/review: тот же --check.
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
const require=createRequire(import.meta.url),bundler=require('next/dist/compiled/webpack/webpack');bundler.init();
const root=fileURLToPath(new URL('../',import.meta.url)),temp=await fs.mkdtemp(path.join(os.tmpdir(),'ab-map-bundle-'));
try{
 const compiler=bundler.webpack({mode:'production',context:root,target:['web','es2020'],
  entry:{runtime:'./public/flight-map/v6/app.js'},
  experiments:{outputModule:true},devtool:false,optimization:{minimize:false},
  output:{path:temp,filename:'[name].js',library:{type:'module'}},
  plugins:[new bundler.webpack.BannerPlugin({banner:'Generated by scripts/build-flight-map-runtime.mjs. Edit v6/app.js, not this bundle.'})]
 });
 await new Promise((resolve,reject)=>compiler.run((error,stats)=>compiler.close(()=>error?reject(error):stats.hasErrors()?reject(Error(stats.toString({all:false,errors:true}))):resolve())));
 for(const name of ['runtime.js']){
  const source=await fs.readFile(path.join(temp,name),'utf8');
  const result=await require('next/dist/compiled/terser').minify(source,{module:true,ecma:2020,format:{comments:/Generated by/}});
  if(!result.code)throw Error('Empty bundle '+name);
  const data=Buffer.from(result.code+'\n');const dest=path.join(root,'public/flight-map/v6',name);
  if(process.argv.includes('--check')){if(!data.equals(await fs.readFile(dest)))throw Error(name+' is stale; rebuild flight map runtime');}
  else await fs.writeFile(dest,data);
  console.log(name+': '+data.length+' bytes'+(process.argv.includes('--check')?' — current':''));
 }
}finally{await fs.rm(temp,{recursive:true,force:true});}
