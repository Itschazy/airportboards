// Может ли прогрев заморозить сам себя: дедлайн тика и ограниченное ожидание in-flight.
//
// ЗАЧЕМ ЭТОТ СТОРОЖ СУЩЕСТВУЕТ. 19–20.09.2026 прогрев простоял двое суток так, что снаружи
// сайт выглядел исправным: ответы 200, страницы целые, борт везде вчерашний. Отказ был
// самоподдерживающийся и состоял из двух звеньев:
//
//   1. очередь выросла (два тика подряд пропущены — просрочены оказались все ярусы), тик
//      перевалил за 600 секунд, и crontab оборвал соединение. Next при обрыве клиента
//      отменяет обработчик на полпути;
//   2. незавершённый промис остался в карте `inflight` НАВСЕГДА. Дальше каждый тик доходил
//      до этого ключа, делал `return pending` и вставал намертво — ответа нет, `warm` не
//      растёт, тайм-аут рвёт соединение снова и оставляет в карте ещё один вечный ключ.
//
// Цена: тринадцать тиков за 29 часов прибавили 175 запросов вместо тридцати тысяч. Лечилось
// только перезапуском процесса, то есть очисткой карты. Оба звена чинятся в коде, и сторож
// существует, чтобы ни одно не вернулось молча: они выглядят как «лишняя перестраховка», а
// их отсутствие ничем не проявляется, пока очередь помещается в тайм-аут.
//
// Проверяется исходник, потому что проверяется именно СВОЙСТВО КОДА. Живую сторону меряет
// check-warm-throughput (возраст бортов) и лог тиков на боксе.
//
// Usage:  node scripts/check-warm-deadline.mjs

import fs from 'node:fs';

/** Сколько ждёт вызывающий: crontab на боксе зовёт тик через curl -m 600. */
const CALLER_TIMEOUT_MS = 600_000;
/** Тайм-аут одного обращения к поставщику в doFetch. */
const FETCH_TIMEOUT_MS = 6_000;

let fails = 0;
const say = (ok, msg) => { if (!ok) fails++; console.log(`  ${ok ? '✓' : '✗'} ${msg}`); };

const SRC = fs.readFileSync('lib/flights.ts', 'utf8');
console.log('может ли прогрев заморозить сам себя\n');

// ── 1. У тика есть собственный дедлайн, и он меньше терпения вызывающего ─────────────────
const dl = /const TICK_DEADLINE_MS = Number\(process\.env\.WARM_TICK_MAX_MS \|\| ([0-9_]+)\)/.exec(SRC);
say(!!dl, dl ? `дедлайн тика объявлен: ${Number(dl[1].replace(/_/g, '')) / 1000} с`
  : 'ДЕДЛАЙНА ТИКА НЕТ: тик снова может работать дольше, чем его ждут, и быть оборванным на полпути');
if (dl) {
  const ms = Number(dl[1].replace(/_/g, ''));
  say(ms < CALLER_TIMEOUT_MS,
    ms < CALLER_TIMEOUT_MS
      ? `дедлайн ${ms / 1000} с меньше тайм-аута вызывающего ${CALLER_TIMEOUT_MS / 1000} с`
      : `ДЕДЛАЙН ${ms / 1000} с НЕ МЕНЬШЕ тайм-аута вызывающего ${CALLER_TIMEOUT_MS / 1000} с — обрыв на полпути снова возможен`);
  // Запас нужен на то, что идёт ПОСЛЕ цикла: сброс кэша страниц и сериализация ответа.
  say(ms <= CALLER_TIMEOUT_MS * 0.8,
    ms <= CALLER_TIMEOUT_MS * 0.8
      ? `запас до обрыва не меньше 20%: ${Math.round(100 - 100 * ms / CALLER_TIMEOUT_MS)}%`
      : `запас до обрыва всего ${Math.round(100 - 100 * ms / CALLER_TIMEOUT_MS)}% — после цикла ещё сбрасывается кэш страниц`);
}
say(/if \(Date\.now\(\) - startedAt > TICK_DEADLINE_MS\)/.test(SRC),
  /if \(Date\.now\(\) - startedAt > TICK_DEADLINE_MS\)/.test(SRC)
    ? 'дедлайн проверяется внутри цикла обхода'
    : 'дедлайн объявлен, но В ЦИКЛЕ НЕ ПРОВЕРЯЕТСЯ — объявление само по себе ничего не ограничивает');

// ── 2. Ожидание чужого запроса ограничено ────────────────────────────────────────────────
say(!/if \(pending\) return pending;/.test(SRC),
  !/if \(pending\) return pending;/.test(SRC)
    ? 'чужой in-flight запрос не отдаётся напрямую'
    : 'ВЕРНУЛСЯ `return pending` БЕЗ ОГРАНИЧЕНИЯ: залипший промис снова заморозит прогрев до перезапуска процесса');

const iw = /const INFLIGHT_WAIT_MS = ([0-9_]+)/.exec(SRC);
say(!!iw, iw ? `предел ожидания in-flight: ${Number(iw[1].replace(/_/g, '')) / 1000} с` : 'предел ожидания in-flight не объявлен');
if (iw) {
  const ms = Number(iw[1].replace(/_/g, ''));
  // Ждать меньше, чем длится само обращение, значит гарантированно бросать живые запросы.
  say(ms > FETCH_TIMEOUT_MS,
    ms > FETCH_TIMEOUT_MS
      ? `предел ${ms / 1000} с больше тайм-аута обращения ${FETCH_TIMEOUT_MS / 1000} с`
      : `предел ${ms / 1000} с НЕ БОЛЬШЕ тайм-аута обращения ${FETCH_TIMEOUT_MS / 1000} с — живые запросы будут брошены впустую`);
}
say(/Promise\.race\(\[p, fallback\]\)/.test(SRC),
  /Promise\.race\(\[p, fallback\]\)/.test(SRC)
    ? 'ожидание устроено гонкой с хранилищем, сам запрос не отменяется'
    : 'гонки с хранилищем нет — ожидание ничем не ограничено');

// ── 3. Ключ снимается с карты и тогда, когда промис не завершился ────────────────────────
say(/setTimeout\(\(\) => \{ if \(inflight\.get\(cacheKey\) === p\) inflight\.delete\(cacheKey\); \}/.test(SRC),
  /setTimeout\(\(\) => \{ if \(inflight\.get\(cacheKey\) === p\) inflight\.delete\(cacheKey\); \}/.test(SRC)
    ? 'ключ снимается с карты принудительно, а не только через finally'
    : 'ПРИНУДИТЕЛЬНОГО СНЯТИЯ НЕТ: у отменённого обработчика finally не срабатывает, и ключ останется вечным');

console.log(fails ? `\nПРОВАЛОВ: ${fails}` : '\nпрогрев не может заморозить сам себя');
process.exit(fails ? 1 : 0);
