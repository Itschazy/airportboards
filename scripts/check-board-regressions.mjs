// Четыре регрессии табло, найденные разбором 13.08 — и почему их не поймал ни один из
// двадцати шести существующих наборов.
//
// Все четыре внесены правками того же дня, все четыре невидимы для проверок, которые
// смотрят на КОДЫ ОТВЕТА и НАЛИЧИЕ элементов: страница отдавалась 200, разметка была
// валидной, тексты переведены. Ломалось соответствие между элементами.
//
//   R1. aria-label озвучивал ПЕРЕЧЁРКНУТОЕ время. В ярлык уходил f.scheduled, а крупно
//       рисуется f.actual || f.scheduled, и f.scheduled стоит тут же с line-through.
//       Замер: 150 строк из 352 (42.6%), у 97 из них статус вообще без числа, то есть
//       показанное время восстановить нечем. Худшее — LED: на экране 00:47, в ярлыке 22:10.
//   R3. Плашка «Все рейсы уже вылетели» стояла на табло ПРИЛЁТОВ: один ключ на оба
//       направления, а под плашкой строки со статусом «Получение багажа». Все 12 локалей.
//   R4. Кнопка «показать ещё» на мёртвом борту вставляла строки ВЫШЕ экрана. Срез идёт с
//       конца (показываем свежее), скрытое лежит в голове, а кнопка стояла снизу: нажатие
//       сдвигало содержимое примерно на 1900 px вверх, сама кнопка исчезала.
//   R5. Часы в плашке шли 12-часовые (en/ar/ko/hi): «Data as of … at 9:00 AM» под строками
//       вида «09:45». Единственный форматтер в файле без явного hourCycle.
//
// Проверка идёт по ИСХОДНИКУ, а не по отданной разметке: три из четырёх дефектов видны
// только в соответствии двух мест кода друг другу, и грепом по HTML их не поймать.
//
// Usage:  node scripts/check-board-regressions.mjs

import fs from 'node:fs';

const SRC = fs.readFileSync('components/FlightBoard.tsx', 'utf8');
let fails = 0;
const say = (ok, msg) => { if (!ok) fails++; console.log(`  ${ok ? '✓' : '✗'} ${msg}`); };

console.log('регрессии табло\n');

// ── R1: ярлык обязан называть то, что нарисовано ─────────────────────────────────────────

// Окно намеренно широкое: между ярлыком и отрисовкой лежат стили строки, и они длинные.
const aria = (SRC.match(/aria-label=\{`([^`]*)`\}[\s\S]{0,3000}?\{f\.actual \|\| f\.scheduled\}/) || [])[1];
say(!!aria, aria ? `ярлык строки: \`${aria}\`` : 'ярлык строки рейса не найден рядом с отрисовкой времени');
if (aria) {
  say(aria.includes('${f.actual || f.scheduled}'),
    'ярлык называет ПОКАЗАННОЕ время (actual || scheduled)');
  say(!/^\$\{f\.scheduled\}/.test(aria),
    'ярлык не начинается с f.scheduled — иначе озвучивается перечёркнутое');
}

// ── R3: плашка знает направление ─────────────────────────────────────────────────────────

say(/t\(mode === 'arrivals' \? 'board_all_past_arr' : 'board_all_past_dep'/.test(SRC),
  'плашка «всё в прошлом» выбирается по направлению');
say(!/'board_all_past'/.test(SRC),
  'общий ключ board_all_past больше не используется');

// Ключи должны быть во ВСЕХ каталогах, иначе локаль напечатает сырой идентификатор.
const missing = [];
for (const f of fs.readdirSync('messages').filter((x) => x.endsWith('.json'))) {
  const ui = JSON.parse(fs.readFileSync(`messages/${f}`, 'utf8')).ui ?? {};
  for (const k of ['board_all_past_dep', 'board_all_past_arr']) if (!ui[k]) missing.push(`${f}:${k}`);
  // Вариант для прилётов не должен говорить о вылете — это и был дефект.
  const arr = ui.board_all_past_arr ?? '';
  const dep = ui.board_all_past_dep ?? '';
  if (arr && dep && arr === dep) missing.push(`${f}: прилёты и вылеты дословно совпадают`);
}
say(!missing.length, missing.length ? `в каталогах: ${missing.join(', ')}` : 'оба ключа есть во всех 12 каталогах и различаются');

// ── R4: кнопка стоит с той стороны, где скрытое ──────────────────────────────────────────

say(/const moreAbove = allPast && !showAll;/.test(SRC),
  'признак «скрытое в голове списка» объявлен');
say(/\{moreAbove && moreButton\}/.test(SRC) && /\{!moreAbove && moreButton\}/.test(SRC),
  'кнопка ставится и над списком, и под ним — по признаку');
// Порядок в разметке: над списком должно идти ДО <ul>.
const above = SRC.indexOf('{moreAbove && moreButton}');
const ul = SRC.indexOf('<ul key={`${mode}:${filter}`}');
const below = SRC.indexOf('{!moreAbove && moreButton}');
say(above > 0 && ul > above && below > ul,
  'порядок верный: кнопка-сверху → список → кнопка-снизу');

// ── R5: часы в плашке ────────────────────────────────────────────────────────────────────

const notice = SRC.match(/dateStyle: 'long', timeStyle: 'short'[^}]*/);
say(!!notice && /hourCycle/.test(notice[0]),
  notice ? `часовой цикл в плашке задан явно: ${/hourCycle: '([^']+)'/.exec(notice[0])?.[1] ?? '—'}`
         : 'форматтер плашки не найден');

// Ни один форматтер времени в файле не должен полагаться на умолчание локали.
const loose = [...SRC.matchAll(/new Intl\.DateTimeFormat\([^)]*\{[^}]*(hour|timeStyle)[^}]*\}/g)]
  .filter((m) => !/hourCycle|hour12/.test(m[0]));
say(!loose.length, loose.length
  ? `форматтеров времени без явного цикла: ${loose.length}`
  : 'все форматтеры времени задают часовой цикл явно');

console.log(fails ? `\nПРОВАЛОВ: ${fails}` : '\nчетыре регрессии табло закрыты');
process.exit(fails ? 1 : 0);
