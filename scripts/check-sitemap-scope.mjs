// Что именно карта сайта предлагает поисковику — и не предлагает ли она пустоту.
//
// Замер Google Search Console 13.08: из 6 630 известных Google адресов проиндексировано
// 1 070, а 5 324 помечены «просканирована, не проиндексирована» — он их скачал, посмотрел и
// отказал. Бюджета хватало с запасом (37 700 запросов, 448 МБ за 90 дней), так что это
// вердикт по содержимому, а не очередь на обход. Средняя позиция у взятых 41.3, кликов за
// квартал двенадцать.
//
// Отвергал он ровно то, что сайт сам и рекламировал: 3 143 страницы аэропортов с измеренным
// НУЛЁМ вылетов — 43% заявленного корпуса. Разбор схожести: такие страницы похожи друг на
// друга на 0.975 при 0.42–0.44 у остальных классов сайта. Та же формулировка стоит в отказе
// AdSense от 03.08 — «бесполезный контент».
//
// Проверка следит за ДВУМЯ границами сразу, и вторая не менее важна первой:
//
//   1. пустое НЕ рекламируется — иначе возвращается тот самый вердикт;
//   2. заявлено РОВНО то, чей борт обновляется не реже раза в два часа, — и всё оно целиком.
//
// 🔴 ГРАНИЦА 2 ПЕРЕПИСАНА 07.10.2026, и прежнюю редакцию стоит знать, потому что она прямо
// запрещала нынешнюю. Она требовала «живое рекламируется ВСЁ, вплоть до аэропортов с одним
// рейсом в сутки» и обосновывала это тем, что хвост кормит: LWN 238 визитов/мес, SUI 280.
// Обоснование верное и осталось в силе — изменился масштаб задачи.
//
// Замер Search Console 07.10: индексирующий бот (Smartphone) сделал 2% от 137 тыс. запросов
// за 90 дней, то есть порядка тридцати обращений в сутки, при 72 020 заявленных адресах и
// доле обнаружения менее 1%. Прежняя редакция защищала хвост от реза по размеру, но против
// бюджета обхода она же работала наоборот: обойти заявленное целиком Google физически не мог
// и не обходил — 6 107 адресов стоят «просканирована, не проиндексирована», 443 в индексе.
//
// Что сохранено дословно: ни один аэропорт не снят ЗА МАЛЫЙ РАЗМЕР. Граница проходит по
// сроку обновления борта, а закрепления по измеренному спросу (lib/warm.ts DEMAND_PINNED)
// входят в карту при любом ярусе — поэтому LWN, SUI, PES и HOR остаются, и остаются
// поимённой проверкой ниже. Снято то, чей борт краулер застаёт вчерашним: ярус small
// обновляется раз в девять часов, mid — раз в три.
//
// Снятие с карты НЕ деиндексирует: страницы остаются связанными (подвал, указатель A–Z — он
// в карте целиком, страницы стран и городов) и объявляют index, follow. Карта отвечает за
// обнаружение, не за удержание, — потому Яндекс, где этих страниц 95 779 и откуда приходит
// 99.7% показов, ничего не теряет.
//
// Usage:  node scripts/check-sitemap-scope.mjs [base]

import fs from 'node:fs';

const BASE = process.argv[2] || 'http://localhost:3002';

const svcRaw = JSON.parse(fs.readFileSync('data/airport-service.json', 'utf8'));
const LEVEL = svcRaw.airports ?? svcRaw;

/**
 * Границу и список закреплений проверка ЧИТАЕТ ИЗ lib/warm.ts, а не повторяет числами.
 *
 * Повторять нельзя: предмет проверки — совпадение карты с предикатом, и своя копия предиката
 * превращает её в спор двух копий. На этом здесь уже обожглись трижды (см. примечание о
 * check-sitemap-scope в CLAUDE.md), каждый раз ошибалась проверка, а не код. Разбор текстом,
 * а не импортом, потому что lib/warm.ts — TypeScript с алиасами '@/…', и тянуть сюда сборку
 * ради трёх констант дороже, чем разобрать объявление, которое ломается заметно: если регэксп
 * ничего не найдёт, проверка падает здесь и сразу, а не молча считает по пустому множеству.
 */
const WARM_SRC = fs.readFileSync('lib/warm.ts', 'utf8');
const mustMatch = (re, what) => {
  const m = WARM_SRC.match(re);
  if (!m) { console.log(`  ✗ не удалось прочитать ${what} из lib/warm.ts — объявление переехало`); process.exit(1); }
  return m;
};
const PINNED = new Set(
  [...mustMatch(/const DEMAND_PINNED = new Set\(\[([\s\S]*?)\]\);/, 'DEMAND_PINNED')[1]
    .matchAll(/'([A-Z0-9]{3})'/g)].map((m) => m[1]),
);
const TIERS = [...mustMatch(/export const TIERS: WarmTier\[\] = \[([\s\S]*?)\];/, 'TIERS')[1]
  .matchAll(/name: '(\w+)', minFlights: (\d+), intervalMin: (\d+)/g)]
  .map((m) => ({ name: m[1], minFlights: Number(m[2]), intervalMin: Number(m[3]) }));
const MAX_INTERVAL = Number(mustMatch(/SITEMAP_MAX_INTERVAL_MIN = (\d+)/, 'SITEMAP_MAX_INTERVAL_MIN')[1]);

const tierOf = (flights) => (!flights || flights < 1 ? null : TIERS.find((t) => flights >= t.minFlights) ?? null);
/** Тот же предикат, что advertisedInSitemap в lib/warm.ts, минус isUnfillable/hasNoService — их стережёт граница 1. */
const advertised = (code) => {
  const t = tierOf(LEVEL[code] ?? 0);
  if (!t) return false;
  return PINNED.has(code) || t.intervalMin <= MAX_INTERVAL;
};

/**
 * Верхняя граница заявленного корпуса. Не догма, а сигнал «мы снова раздулись».
 *
 * История числа, потому что двигать его можно только с ней в руках:
 *
 *   87 924  до 13.08 — состояние, за которое Google пометил 5 324 адреса «просканирована,
 *                      не проиндексирована», а AdSense отклонил сайт за «бесполезный контент»;
 *   64 560  после реза 43% корпуса (страницы с измеренным нулём вылетов);
 *   71 160  после 14.08 — порог ARRIVALS_MIN_DAILY снижен с 40 до 10, и в карту вернулись
 *                         1 045 подстраниц прилётов вместо 462.
 *
 * Рост осознанный и обратный по смыслу тому, что резали: тогда убирали страницы, которым
 * нечего показать, теперь добавляют страницы с 19–39 строками на борту и измеренным спросом
 * (KZN 30 266 показов, UFA 28 320). Класс запросов «прилёт» даёт лучший CTR на сайте — 3.0%.
 *
 *   72 020  замер прода 07.10 перед сужением;
 *   24 000  потолок после сужения 07.10 по сроку обновления борта.
 *
 * Прежний потолок 76 000 выражал другую мысль — «мы снова раздулись против 13.08». Нынешний
 * выражает первую: полное насыщение после сужения — 1 699 путей (474 борта + 463 кандидата
 * прилётов + 484 маршрута + 147 городов + 97 стран + 26 указателей + статика), то есть
 * 20 388 URL на двенадцати языках. Потолок 24 000 оставляет 18% на аэропорты, которые
 * поднимутся в ярусе или получат закрепление при следующем замере спроса.
 *
 * ⚠️ Двигать его вверх можно только вместе с границей в lib/warm.ts: число здесь — следствие
 * границы, а не отдельное решение, и разъехавшись они перестанут значить что-либо.
 */
const MAX_DECLARED = 24_000;
/**
 * И нижняя граница — на проде. Карта, схлопнувшаяся вдвое, выглядит снаружи так же нормально,
 * как раздувшаяся: 200, валидный XML, закрывающий тег на месте. 24.09 сборка прочитала
 * хранилище посреди записи и запекла карту без прилётов и маршрутов; тогда это поймали
 * отдельные проверки на ноль, но только потому, что пропали ВСЕ. Пол ловит и половину.
 */
const MIN_DECLARED = 12_000;
const LOCALES = 12;

let fails = 0;
const say = (ok, msg) => { if (!ok) fails++; console.log(`  ${ok ? '✓' : '✗'} ${msg}`); };

console.log(`область карты сайта (${BASE})\n`);

// ── Собираем всё, что карта заявляет ──────────────────────────────────────────────────────

const index = await (await fetch(`${BASE}/sitemap.xml`, { headers: { 'user-agent': 'audit-bot' } })).text();
const children = [...index.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
say(children.length > 0, `детей у индекса карты: ${children.length}`);

const locs = [];
for (const url of children) {
  const path = new URL(url).pathname;
  const xml = await (await fetch(`${BASE}${path}`, { headers: { 'user-agent': 'audit-bot' } })).text();
  for (const m of xml.matchAll(/<loc>([^<]+)<\/loc>/g)) locs.push(m[1]);
}

const inMap = new Set(
  locs.map((l) => /\/en\/airport\/([A-Z0-9]{3})$/.exec(l)?.[1]).filter(Boolean)
);

/**
 * С 24.09.2026 каждый язык — отдельный <loc> (app/sitemap.ts, entry). Раньше карта держала
 * только английские адреса, а языки жили альтернативами внутри них, поэтому корпус считался
 * как «записи × 12». Теперь записи и есть корпус: умножать — значит насчитать 144 языка и
 * покраснеть на ровном месте. Потолок MAX_DECLARED при этом не меняется: он всегда был в
 * адресах с учётом языков.
 */
console.log(`  записей <loc>: ${locs.length}, из них страниц аэропортов (en): ${inMap.size}`);
console.log(`  заявлено URL на ${LOCALES} языках: ${locs.length.toLocaleString('ru-RU')}\n`);

say(locs.length <= MAX_DECLARED,
  `корпус в пределах ${MAX_DECLARED.toLocaleString('ru-RU')} URL`);
// Пол — только против прода: локальная сборка поднимается на фикстуре, где прилётов и
// маршрутов нет по построению, и корпус там короче боевого законно.
if (/^https:\/\/airportsboard\.live/.test(BASE)) {
  say(locs.length >= MIN_DECLARED,
    locs.length >= MIN_DECLARED
      ? `корпус не ниже ${MIN_DECLARED.toLocaleString('ru-RU')} URL`
      : `корпус схлопнулся до ${locs.length.toLocaleString('ru-RU')} URL при полу ${MIN_DECLARED.toLocaleString('ru-RU')} — карта запечена не с тем хранилищем или сломан предикат`);
}

// ── 1. Пустое не рекламируется ────────────────────────────────────────────────────────────

/**
 * Неподтверждённые нули из проверки ИСКЛЮЧЕНЫ — так же, как их исключает сам код.
 *
 * serviceLevel() возвращает для них null, то есть «замер дал ноль, но мы ему не верим»,
 * и hasNoService их намеренно не трогает. Первая версия этой проверки об этом не знала и
 * обвиняла код в рекламе 1 177 страниц, которые он держит осознанно. Проверка обязана
 * повторять предикат, а не изобретать свой, иначе она спорит с кодом, а не стережёт его.
 */
let unverified = new Set();
try {
  const u = JSON.parse(fs.readFileSync('data/airport-service-unverified.json', 'utf8'));
  // Коды лежат в поле `codes`, а не ключами верхнего уровня — там метаданные замера.
  const codes = Array.isArray(u) ? u : (u.codes ?? Object.keys(u));
  unverified = new Set(Array.isArray(codes) ? codes : Object.keys(codes));
} catch { /* файла нет — значит и исключений нет */ }

const zeros = Object.entries(LEVEL)
  .filter(([c, n]) => n === 0 && !unverified.has(c))
  .map(([c]) => c);
/**
 * Вики-маршруты дают странице содержание даже при нуле измеренных вылетов: она отвечает на
 * вопрос «кто летает и куда» и перестаёт быть страницей об отсутствующем. hasNoService их
 * намеренно не трогает, поэтому и проверка не должна.
 *
 * Источник и предикат взяты ТЕ ЖЕ, что в lib/wiki-routes.ts hasWikiAirlines: файл
 * airport-wiki-routes.json и непустой список airlines. Сначала я смотрел в airport-routes.json
 * с другой формой записи, и проверка обвиняла код в рекламе 276 страниц, которые он держит
 * осознанно. Расхождение проверки с предикатом — это спор с кодом, а не охрана его.
 */
let wiki = {};
try {
  const raw = JSON.parse(fs.readFileSync('data/airport-wiki-routes.json', 'utf8'));
  wiki = raw.airports ?? raw;
} catch { /* файла нет — значит и исключений нет */ }
const hasWiki = (c) => {
  const e = wiki[c];
  return !!e && Array.isArray(e.airlines) && e.airlines.length > 0;
};

const advertisedEmpty = zeros.filter((c) => !hasWiki(c) && inMap.has(c));
say(advertisedEmpty.length === 0,
  advertisedEmpty.length
    ? `карта рекламирует ${advertisedEmpty.length} страниц с нулём вылетов: ${advertisedEmpty.slice(0, 6).join(', ')}…`
    : `страниц с нулём вылетов в карте нет (проверено ${zeros.length} кандидатов)`);

// ── 2. Заявлено ровно свежее — и всё свежее ───────────────────────────────────────────────

const served = Object.entries(LEVEL).filter(([, n]) => (n ?? 0) > 0).map(([c]) => c);
const expected = served.filter(advertised);
console.log(`  · граница: борт обновляется не реже ${MAX_INTERVAL} мин (ярусы ${TIERS.filter((t) => t.intervalMin <= MAX_INTERVAL).map((t) => t.name).join('/')}) + ${PINNED.size} закреплений по спросу`);
console.log(`  · ожидается в карте ${expected.length} аэропортов из ${served.length} обслуживаемых\n`);

const missing = expected.filter((c) => !inMap.has(c));
// Закрытые аэропорты выпадают законно — их отсеивает isUnfillable/сам корпус.
say(missing.length <= expected.length * 0.05,
  missing.length
    ? `не заявлено ${missing.length} из ${expected.length} аэропортов внутри границы (${(100 * missing.length / expected.length).toFixed(1)}%): ${missing.slice(0, 6).join(', ')}…`
    : `все ${expected.length} аэропортов внутри границы заявлены`);

/**
 * Обратная граница, и она здесь главная.
 *
 * Без неё правка 07.10 держится на одной строке в app/sitemap.ts: убери её — и проверка
 * промолчит, потому что первое утверждение «всё ожидаемое на месте» от лишнего не краснеет.
 * Ровно так сужение и откатывается молча при следующем рефакторинге.
 */
const extra = [...inMap].filter((c) => (LEVEL[c] ?? 0) > 0 && !advertised(c));
say(extra.length === 0, extra.length
  ? `карта заявляет ${extra.length} аэропортов за границей свежести: ${extra.slice(0, 8).join(', ')}…`
  : 'за границей свежести в карте никого');

/**
 * Отдельно и строго: самые маленькие из тех, что реально кормят трафиком.
 *
 * Эти четыре — причина, по которой граница проходит по сроку обновления, а не по числу
 * рейсов: у всех четырёх рейсов мало, все четыре в DEMAND_PINNED, и попадают они в карту
 * через закрепление. Проверка оставлена дословно из прежней редакции и теперь сторожит
 * именно слагаемое с закреплениями: если его когда-нибудь потеряют, упадёт здесь.
 */
const TINY_BUT_ALIVE = [['LWN', 'Гюмри, 238 визитов/мес'], ['SUI', 'Сухум, 280'], ['PES', 'Петрозаводск'], ['HOR', 'Орта']];
for (const [c, why] of TINY_BUT_ALIVE) {
  if ((LEVEL[c] ?? 0) <= 0) continue;
  say(PINNED.has(c), `${c} закреплён по спросу — ${why}`);
  say(inMap.has(c), `${c} (${LEVEL[c]} вылетов/сут) в карте — ${why}`);
}

// ── 3. Прилёты заявлены там, где на них есть спрос ────────────────────────────────────────

/**
 * Порог ARRIVALS_MIN_DAILY снижен с 40 до 10 — и это ровно та граница, которая до 14.08
 * выбрасывала из карты самые прибыльные страницы сайта.
 *
 * Замер Вебмастера по 500 запросам (108 896 показов): класс «прилёт» даёт CTR 3.0%, лучший из
 * всех классов (вылет 2.6%, «табло» без направления 1.5%). А подстраница прилётов не была
 * заявлена у KZN (29 вылетов/сут, 30 266 показов), UFA (25 — 28 320), AER (39 — 4 418),
 * CEK (15 — 3 683), MRV (19 — 3 204). Все они отвечали 200 с index, follow и 19–39 строками на
 * борту: страницы были, поисковику про них не говорили.
 *
 * Проверка осмысленна ТОЛЬКО против прогретого хранилища — прилёты отбираются по живым строкам
 * борта, и на холодной локальной машине их в карте не будет ни одной. Поэтому ноль прилётов
 * трактуется как «нечего проверять», а не как провал: иначе проверка ловила бы состояние
 * машины вместо состояния кода. Ровно на этом уже спотыкались 13.08, когда локальные 4 464
 * записи выглядели пропавшим выкатом, а на деле отличались только прогревом.
 */
const arrivals = new Set(
  locs.map((l) => /\/en\/airport\/([A-Z0-9]{3})\/arrivals$/.exec(l)?.[1]).filter(Boolean)
);
const ARRIVALS_MIN_DAILY = 10;

/**
 * 🔴 ПРОПУСК ТОЛЬКО ЛОКАЛЬНО. На ПРОДЕ ноль — авария, а не «нечего проверять».
 *
 * Пропуск выше писался против холодной локальной машины и различал не то: не «прогрето ли
 * хранилище», а «есть ли в карте прилёты». 24.09.2026 это обернулось дырой. Сборка прочитала
 * хранилище посреди записи (lib/flightStore.ts persist, запись была неатомарной), решила, что
 * оно пустое, и запекла карту без единого прилёта и маршрута — минус 1 549 путей на двенадцати
 * языках, причём тех, что дают лучший CTR сайта. Ежедневный прогон в 22:21 увидел ноль, счёл
 * хранилище холодным, пропустил проверку и напечатал «карта предлагает всё живое». Нашлось
 * только при ручной перепроверке следующей ночью.
 *
 * Прод прогревается круглосуточно, так что холодным его хранилище не бывает; ноль там значит,
 * что КАРТА собрана не с тем хранилищем. То же для маршрутов: их отбирает тот же getRoute по
 * тому же хранилищу, и пропадают они вместе с прилётами.
 */
const IS_PROD = /^https:\/\/airportsboard\.live/.test(BASE);
const routesInMap = locs.filter((l) => /\/en\/route\//.test(l)).length;
if (IS_PROD) {
  say(routesInMap > 0, routesInMap > 0
    ? `маршрутов в карте: ${routesInMap}`
    : 'на ПРОДЕ в карте НОЛЬ маршрутов — карта запечена с пустым хранилищем (сборка прочитала его битым?)');
}
if (!arrivals.size) {
  if (IS_PROD) say(false, 'на ПРОДЕ в карте НОЛЬ подстраниц прилётов — карта запечена с пустым хранилищем, а не «хранилище холодное»');
  else console.log(`  · прилётов в карте нет — хранилище холодное (локальная база), проверка яруса пропущена`);
} else {
  console.log(`  · подстраниц прилётов в карте: ${arrivals.size}`);
  // Денежные направления: без них снижение порога не состоялось.
  const MONEY_ARRIVALS = [['KZN', '30 266 показов'], ['UFA', '28 320'], ['AER', '4 418'], ['CEK', '3 683'], ['MRV', '3 204']];
  for (const [c, why] of MONEY_ARRIVALS) {
    if ((LEVEL[c] ?? 0) < ARRIVALS_MIN_DAILY) continue;   // ярус изменился — не наше дело
    if (!inMap.has(c)) continue;                          // сам борт не заявлен — другая проверка
    say(arrivals.has(c), `${c} (${LEVEL[c]}/сут): прилёты в карте — ${why}`);
  }
  // Обратная граница: ниже порога прилётов быть не должно. Если появились — сломался ярус, и
  // карта снова потащит за собой хвост пустых «рейсов нет», за который уже прилетало.
  const belowTier = [...arrivals].filter((c) => (LEVEL[c] ?? 0) < ARRIVALS_MIN_DAILY);
  say(belowTier.length === 0, belowTier.length
    ? `прилёты заявлены ниже яруса ${ARRIVALS_MIN_DAILY}: ${belowTier.slice(0, 6).join(', ')}…`
    : `ни одной подстраницы прилётов ниже яруса ${ARRIVALS_MIN_DAILY}`);
  // И не больше, чем есть кандидатов: гейт по строкам обязан отсеивать, а не пропускать всё.
  const candidates = Object.entries(LEVEL).filter(([c, n]) => (n ?? 0) >= ARRIVALS_MIN_DAILY && inMap.has(c)).length;
  say(arrivals.size <= candidates,
    `прилётов ${arrivals.size} при ${candidates} кандидатах яруса — гейт по строкам работает`);
}

console.log(fails
  ? `\nПРОВАЛОВ: ${fails}`
  : '\nкарта предлагает ровно свежее: ничего пустого, ничего из хвоста, и всё, что внутри границы');
process.exit(fails ? 1 : 0);
