'use client';

import dynamic from 'next/dynamic';

// Localized not-found входит в дерево layout даже на исправной странице табло.
// Прямой импорт AirportSearch заставлял Next включать поиск и общий с главной
// chunk в начальные script-теги каждого аэропорта. Телефон скачивал и разбирал
// этот код, хотя поиск аэропортов здесь никогда не отображается.
// Клиентская граница с dynamic отделяет его от начального графа. SSR оставлен
// включённым, чтобы не вводить дополнительный переход на клиентский рендер.
// Поиск загружается при отображении самой 404. На главной остаётся прямой импорт,
// без задержки поиска.
// Проверка: сравнение script-тегов production-сборок и поиск на настоящей 404;
// SSR/SEO табло отдельно сравниваются на всех 12 локалях.
export const NotFoundSearch = dynamic(() =>
  import('./AirportSearch').then(module => module.AirportSearch)
);
