export const locales = ['en', 'ru', 'zh', 'ar', 'de', 'ko', 'ja', 'fr', 'es', 'it', 'hi', 'tr'] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = 'en';

export const rtlLocales: Locale[] = ['ar'];

/**
 * Система счисления задаётся ЯВНО — потому что ICU на разных хостах решает по-разному.
 *
 * Замер 12.08.2026. Один и тот же код, одна и та же строка каталога «تم التحديث قبل
 * {h, number} ساعة»:
 *   - на маке (Node 20.13, ICU 75.1 full) → «قبل ٥ ساعة», восточные цифры;
 *   - на боевом сервере               → «قبل 5 ساعة», западные.
 * На проде при этом не нашлось НИ ОДНОЙ восточной цифры на всех арабских страницах, тогда как
 * ru/de/fr/tr форматировались правильно всюду (2 801 неразрывным пробелом, 2.801, 2 801 узким
 * неразрывным) — то есть ICU там полный, и расходится ровно выбор системы счисления для «ar».
 * Проверяется в одну строку: Intl.NumberFormat('ar') даёт arab, а Intl.NumberFormat('ar-AE') —
 * latn, и вывод прода совпадает со вторым посимвольно.
 *
 * Это дефект сам по себе, независимо от того, какие цифры считать правильными: сайт не должен
 * выглядеть по-разному от того, как собран Node на машине. Проверить арабскую вёрстку локально
 * было НЕВОЗМОЖНО — она отличалась от боевой.
 *
 * Выбран latn, и вот почему. Половину чисел на табло вообще нельзя перевести в другую систему:
 * время рейса «06:10», номер «EY63», выход «B11» приезжают строками от поставщика данных.
 * Если счётчик над ними печатает «٨٠ رحلة مغادرة», в одном экране оказываются две системы
 * счисления — ровно та несогласованность, ради которой правку и затевали, только наполовину.
 * К тому же в авиации Залива (Emirates, Dubai Airports, Saudia) арабские интерфейсы держат
 * западные цифры, а прод и так отдавал их всю свою жизнь — читатель ничего не заметит.
 *
 * Развернуть решение — поменять здесь 'latn' на 'arab'. Всё остальное подтянется само.
 */
export const NUMERAL_SYSTEM: Partial<Record<Locale, string>> = { ar: 'latn' };

/** 'ar-u-nu-latn' → 'ar'. Нужна, чтобы локаль форматирования не утекала туда, где ждут код. */
export const baseLocale = (locale: string): string => (locale || '').split('-u-')[0];

/**
 * Локаль ДЛЯ ФОРМАТИРОВАНИЯ чисел и дат — не для lang, hreflang, ссылок и имён файлов.
 * Расширение -u-nu-… понимают и Intl, и ICU MessageFormat, поэтому одной этой строкой
 * закрываются оба пути: и toLocaleString в компонентах, и {x, number} в каталогах.
 */
export function numLocale(locale: string): string {
  const base = baseLocale(locale);
  const nu = NUMERAL_SYSTEM[base as Locale];
  return nu ? `${base}-u-nu-${nu}` : base;
}

