/**
 * «de» перед именем собственным во французском: «de Paris», но «d’Amsterdam».
 *
 * Элизия во французском обязательна, а шаблоны печатали «de» всегда, поэтому заголовок
 * страницы города читался «Aéroports de Amsterdam», а H2 на странице аэропорта — «Autres
 * aéroports près de Istanbul». Из 5592 французских названий городов и 6070 названий
 * аэропортов больше тысячи начинаются с гласной.
 *
 * Правило намеренно уже, чем «первая буква — гласная», потому что наивная версия портит
 * больше, чем чинит:
 *
 *   - h НЕ элидируется по умолчанию. Французское h бывает немым («d’Helsinki») и придыхательным
 *     («de Hambourg», «de Hanovre», «de Hong Kong»), и машинного признака, который их различает,
 *     не существует — это свойство французского экзонима, а не исходного языка. Безопасная
 *     сторона здесь «de»: пропущенная элизия читается как небрежность, лишняя — как ошибка.
 *   - y НЕ элидируется: начальное y даёт согласный звук — «de York», «de Yokohama»,
 *     «de Yamoussoukro», а не «d’York».
 *   - нелатинское начало НЕ элидируется: «de 北京». Определять элизию по кодовой точке
 *     иероглифа бессмысленно — она зависит от того, как название читают по-французски.
 *   - французский артикль в составе названия стягивается с предлогом, а не элидируется:
 *     «Le Havre» → «du Havre», «Les Sables» → «des Sables», «L’Aigle» → «de l’Aigle».
 *     Иностранная фиксированная часть артиклем не считается: «de Los Angeles», «de Las Vegas».
 *
 * Возвращает предлог ВМЕСТЕ с именем, потому что в «du Havre» они срослись и разделить их
 * в шаблоне нельзя.
 */

/** Гласные, включая диакритику и лигатуры. Без y и без h — см. пояснение выше. */
const VOWEL = /^[aàáâãäåāăąeèéêëēĕėęěiìíîïĩīĭįıoòóôõöøōŏőuùúûüũūŭůűųæǽœ]/i;

/**
 * Аббревиатура читается по буквам, поэтому элизия зависит от НАЗВАНИЯ первой буквы, а не от
 * того, гласная она или согласная: «de KZN» (ка), но «d’IST» (и), «d’AMS» (а), «d’MSQ» (эм).
 * Буквы, чьё французское название начинается с гласного звука: a, e, f (èfe), h (ache),
 * i, l (èle), m (ème), n (ène), o, r (ère), s (èse), u, x (ixe), y (i grec).
 */
const ACRONYM = /^[A-Z0-9]{2,4}$/;
const VOWEL_LETTER_NAME = /^[AEFHILMNORSUXY]/;

export function frDe(name: string): string {
  const n = (name ?? '').trim();
  if (!n) return 'de';

  if (ACRONYM.test(n)) return VOWEL_LETTER_NAME.test(n) ? `d’${n}` : `de ${n}`;

  // Артикль в составе французского топонима: предлог сливается с ним.
  if (/^Les\s+/.test(n)) return `des ${n.slice(4).trim()}`;
  if (/^Le\s+/.test(n)) return `du ${n.slice(3).trim()}`;
  if (/^L['’]/.test(n)) return `de l’${n.slice(2).trim()}`;

  return VOWEL.test(n) ? `d’${n}` : `de ${n}`;
}

/**
 * То же для локалей, где предлог не нужен: остальные каталоги подставляют голое имя, а этот
 * параметр просто не используется их строками. Возвращаем имя как есть, чтобы случайно
 * попавший в чужой шаблон параметр не напечатал французский предлог.
 */
export function deName(name: string, locale: string): string {
  return locale === 'fr' ? frDe(name) : name;
}
