/**
 * Одна точка для событий: Яндекс.Метрика и Google Analytics одновременно.
 *
 * ЗАЧЕМ. Аудит удобства 12.08.2026 упёрся в то, что половину вопросов о продукте закрыть
 * нечем: во всём проекте не было НИ ОДНОГО reachGoal. Прямые следствия, каждое реальное:
 *
 *   - неизвестно, пользуются ли вкладкой «Прилёты». Переключение не меняет URL, поэтому
 *     /ru/airport/KZN/arrivals имеет 0 просмотров при 3 382 у родителя — и это ничего не
 *     говорит о вкладке, только о том, что по прямой ссылке туда заходят редко;
 *   - неизвестно, открывают ли карточку рейса. А это единственное осмысленное действие на
 *     странице, и именно им проверяется гипотеза про десктопные отказы: на ПК отказы 23%
 *     против 14.8% на мобильных при вдвое меньшей длительности. Если карточку на ПК
 *     открывают чаще — «отказ» там означает БЫСТРЫЙ ответ, а не плохой, и десктопную цифру
 *     надо перестать считать проблемой. Без события это неразрешимо;
 *   - неизвестно, доскролливают ли до кнопки «показать ещё» и трогают ли фильтры — то есть
 *     нечем взвесить любую правку первого экрана.
 *
 * УСТРОЙСТВО. Отправляется в оба счётчика, потому что они покрывают разные части аудитории:
 * Метрика подключена ТОЛЬКО на русской локали (см. YandexMetrica.tsx — tag.js весит ~93 КБ
 * gzip и мерит рынок, который AdSense не монетизирует), GA — везде. На /ru сработают оба,
 * на остальных локалях только GA; расхождение между ними ожидаемо и не является ошибкой.
 *
 * МОЛЧИТ, КОГДА СЧЁТЧИКОВ НЕТ. Ни один вызов не обязан существовать: Метрики нет вне ru, GA
 * нет без NEXT_PUBLIC_GA_ID, оба отсутствуют на сервере. Всё обёрнуто, событие — не повод
 * уронить интерфейс.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ ДОЛЖНО БЫТЬ. Ничего, что относится к конкретному человеку: ни номера
 * рейса, ни поискового запроса, ни координат. Параметры — только категориальные: какая
 * вкладка, какой фильтр, есть ли на борту будущие рейсы. Этого хватает на все вопросы выше
 * и не хватает, чтобы кого-то узнать.
 *
 * ЦЕЛИ В ИНТЕРФЕЙСЕ МЕТРИКИ. reachGoal с новым идентификатором сам цель не создаёт: пока её
 * не завели в счётчике, событие уходит и не показывается в отчётах. Список — в GOALS ниже.
 */

/**
 * Сигнатуры намеренно те же, что в components/YandexMetricaRouteTracker.tsx.
 *
 * `declare global` из разных файлов СЛИВАЕТСЯ, и расхождение хотя бы в одном параметре —
 * ошибка сборки «Subsequent property declarations must have the same type», а не тихое
 * переопределение. Поэтому здесь стоит общий вариант, а не более точный.
 */
declare global {
  interface Window {
    ym?: (...args: unknown[]) => void;
    gtag?: (...args: unknown[]) => void;
  }
}

/**
 * Идентификаторы целей. Держатся здесь списком, чтобы их можно было слово в слово завести в
 * интерфейсе Метрики и чтобы опечатка в вызове была видна глазами, а не через месяц пустого
 * отчёта.
 */
export const GOALS = {
  /** Открыта карточка рейса — главное действие страницы. */
  flightCard: 'flight_card',
  /** Переключена вкладка вылет/прилёт. Параметр: mode. */
  boardMode: 'board_mode',
  /** Нажат фильтр по статусу. Параметр: filter. */
  boardFilter: 'board_filter',
  /** Раскрыт полный список рейсов. */
  boardMore: 'board_more',
  /** Выбран аэропорт в поиске. */
  searchPick: 'search_pick',
} as const;

export type Goal = (typeof GOALS)[keyof typeof GOALS];

/** Идентификатор счётчика Метрики. Дублируется из YandexMetrica.tsx намеренно: */
/*  импорт серверного компонента в клиентский модуль тянул бы за собой весь его граф. */
const YM_ID = 110112198;

/**
 * Отправить событие. Безопасно вызывать откуда угодно, включая серверный рендер.
 *
 * @param goal   идентификатор из GOALS
 * @param params только категориальные значения; ничего, что относится к человеку
 */
export function track(goal: Goal, params?: Record<string, string | number | boolean>): void {
  if (typeof window === 'undefined') return;
  try {
    window.ym?.(YM_ID, 'reachGoal', goal, params);
  } catch { /* счётчик не должен ломать интерфейс */ }
  try {
    window.gtag?.('event', goal, params);
  } catch { /* то же */ }
}
