import fs from 'node:fs';
import path from 'node:path';

/**
 * Адрес движка карты вместе с отпечатком сборки.
 *
 * Путь `/flight-map/v9/runtime.js` между выкатами НЕ меняется, а отдаётся файл
 * с `Cache-Control: immutable` на год. Пока менялся только сам движок, это
 * работало; стоило вместе с ним измениться разметке страницы — и вернувшийся
 * человек получал НОВЫЙ HTML со СТАРЫМ движком из своего кэша. Старый движок
 * искал в разметке элементы, которых там уже нет, падал на первом же обращении
 * к ним и оставлял все кнопки выключенными: страница выглядела мёртвой.
 *
 * Отпечаток берётся из размера и времени файла, поэтому меняется ровно тогда,
 * когда пересобран бандл, и не трогает кэш в остальное время. Считается один
 * раз при загрузке модуля на сервере — в отдачу страницы это не попадает.
 */
export const runtimeUrl = (() => {
  const base = '/flight-map/v9/runtime.js';
  try {
    const stat = fs.statSync(path.join(process.cwd(), 'public', 'flight-map', 'v9', 'runtime.js'));
    return `${base}?b=${stat.size.toString(36)}${Math.round(stat.mtimeMs).toString(36)}`;
  } catch {
    // Нет доступа к файлу — отдаём путь без отпечатка: это ровно прежнее
    // поведение, страница работает, просто кэш не сбрасывается.
    return base;
  }
})();
