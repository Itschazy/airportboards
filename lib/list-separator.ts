/**
 * Разделитель перечисления для локали: «Пн, Вт, Ср», но «الاثنين، الأربعاء» и «月、火、水».
 *
 * Таблица дней недели склеивалась через хардкод `', '` во всех двенадцати локалях, поэтому
 * арабская страница печатала латинскую запятую внутри арабской строки, а китайская и японская —
 * вместо принятой у них разделительной запятой «、» (U+3001). Это не косметика: латинская
 * запятая в арабском тексте — нейтральный по направлению символ, и на границе арабского и
 * латинского фрагмента она уезжает не туда, куда ожидает читатель.
 *
 * `Intl.ListFormat` здесь НЕ подходит, хотя выглядит как готовое решение: он вставляет союз, а
 * не разделитель. Замерено на трёх элементах — ru «A, B и C», ar «A وB وC», zh «A、B和C».
 * Для перечисления дней вылета союз не нужен вовсе, нужен именно знак между элементами, и он
 * из ListFormat напрямую не достаётся: у арабского в `type: 'conjunction'` запятой нет совсем,
 * а нужный «،» появляется только в `type: 'unit'` и склеен там с «و».
 *
 * Список короткий и стабильный — это свойство письменности, а не языка, и меняется оно не чаще,
 * чем сама письменность.
 */
const SEPARATORS: Record<string, string> = {
  ar: '، ',   // арабская запятая U+060C
  zh: '、',   // идеографическая запятая U+3001, без пробела — он в CJK не нужен
  ja: '、',
};

export function listSeparator(locale: string): string {
  return SEPARATORS[locale.split('-')[0]] ?? ', ';
}

/** Склеить перечисление разделителем этой локали. */
export function joinList(items: string[], locale: string): string {
  return items.join(listSeparator(locale));
}
