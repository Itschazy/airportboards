/**
 * Разметка JSON-LD для вставки в <script type="application/ld+json">.
 *
 * 🔴 ЗАЧЕМ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ. Содержимое <script> браузер читает как «сырой текст» и
 * ищет в нём ровно одну последовательность — `</script`. Всё, что до неё, тегами не является,
 * а всё, что после, разбирается уже как HTML. Значит строка `</script><img onerror=…>`, попав
 * внутрь разметки, закрывает тег раньше времени и превращает остаток в живую вёрстку. Экранировать
 * нужно только `<`: `>` тега не открывает, а мнемоники (`&amp;`) внутри script не раскрываются
 * вовсе, поэтому `&` трогать не надо — и не надо делать вид, что это общая «санитизация».
 *
 * Данные в разметку приходят не только свои. Название перевозчика — это
 * `AIRLINE[iata] ?? iata` (lib/flights.ts), подпись аэропорта при неизвестном городе — просто
 * `iata` (airportLabel там же), и оба значения берутся из ответа поставщика. Оттуда они
 * попадают в ответы FAQ (`faq_airlines_a`, `faq_dest_a` в components/AirportBottom.tsx), а
 * ответы — в FAQPage. То есть между чужими данными и контекстом скрипта не было ничего.
 *
 * Аудит 31.10.2026 насчитал 23 места вставки: экранирование стояло В ОДНОМ (страница карты
 * рейсов), остальные двадцать два отдавали голый JSON.stringify. Замер живой страницы Казани
 * показал восемь блоков разметки и ни одного сырого `<`, то есть дыра была спящей, а не
 * открытой, — но зависела она от добросовестности поставщика, а не от нашего кода.
 *
 * Возвращает объект для dangerouslySetInnerHTML целиком, а не строку: так у вызывающего не
 * остаётся места, где можно забыть вызвать помощника.
 */
export function ldScript(data: unknown): { __html: string } {
  // JSON.stringify(undefined) возвращает undefined, а не строку: без подстраховки
  // необязательная схема роняла бы страницу на .replace вместо того, чтобы ничего не напечатать.
  return { __html: (JSON.stringify(data) ?? 'null').replace(/</g, '\\u003c') };
}
