/** Каждый путь навсегда принадлежит одному файлу при неизменном count.
 *
 * Было: равные срезы общего массива. Прилёты и маршруты зависят от хранилища,
 * а дочерние ISR-файлы/процессы могут видеть разные снимки. Добавление даже
 * одного пути сдвигало границы: 18.10.2026 проверка нашла 12 дублей и неполные
 * языковые группы MAA/arrivals и MAD. Сортировка не делает такие срезы стабильными.
 *
 * Теперь корзина определяется только путём БЕЗ локали. Добавление/удаление
 * соседнего адреса не переносит прежние адреса между файлами; все 12 переводов
 * живут вместе. Состав самой карты, предикаты пустых бортов и lastmod сохраняются.
 * Регрессия двух разных снимков: scripts/check-sitemap-shards.mjs.
 */
export function sitemapShard<T extends { url: string }>(all: T[], id: number, count: number): T[] {
  return all.filter(({ url }) => {
    const path = new URL(url).pathname.replace(/^\/[a-z]{2}(?=\/|$)/, '');
    let hash = 2166136261;
    for (let i = 0; i < path.length; i++) hash = Math.imul(hash ^ path.charCodeAt(i), 16777619) >>> 0;
    return hash % count === id;
  });
}
