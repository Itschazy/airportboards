import { getAirport, getCountries, POPULAR_AIRPORTS, POPULAR_AIRPORTS_RU, type CountryInfo } from '@/lib/airports';
import { DEMAND_PINNED } from '@/lib/warm';

/**
 * Порядок стран для каталога на главной — по спросу, а не по числу аэропортов.
 *
 * Зачем вообще. getCountries() сортирует по количеству аэропортов, и на главной это
 * давало «США — Канада — Австралия — Китай — Бразилия»: по числу полос верно, по живому
 * спросу бессмысленно. У Канады 379 аэропортов и почти ноль визитов.
 *
 * ПЕРВАЯ ВЕРСИЯ ЭТОГО МОДУЛЯ СЧИТАЛА НЕПРАВИЛЬНО, и ошибка стоит того, чтобы её здесь
 * записать: страна получала место своего ЛУЧШЕГО аэропорта. Египет с двумя аэропортами
 * (HRG 1-е место, SSH 2-е) обгонял Турцию с четырьмя (AYT 3-е, IST 4-е, BJV 9-е,
 * DLM 12-е), хотя сумма у Турции заметно больше. Считать надо ВСЕ аэропорты страны.
 */

/**
 * Вес места в замере.
 *
 * Взят из самого замера, а не придуман: в комментарии к POPULAR_AIRPORTS_RU записаны
 * шесть из шестнадцати чисел — 3 630, 3 129, 2 917 на первых местах и 903, 860, 639 на
 * последних. Середина линейно интерполирована между известными концами.
 *
 * Разброс между первым и последним выходит 5.7×. Простое «шестнадцать минус номер» дало
 * бы 16× — то есть считало бы, что визиты падают втрое резче, чем они падают на самом
 * деле, и одна страна с первым местом перевешивала бы любую другую с тремя средними.
 *
 * Для одиннадцати неродных локалей чисел нет вовсе: POPULAR_AIRPORTS подбирался под
 * охват, а не по замеру. Там та же кривая применяется к их собственному списку — форма
 * спада у посещаемости обычно одна, а ничего точнее про эти локали не измерено.
 */
const RANK_WEIGHT = [3630, 3129, 2917, 2734, 2551, 2368, 2185, 2002, 1818, 1635, 1452, 1269, 1086, 903, 860, 639];

export function getCountriesByDemand(locale: string): CountryInfo[] {
  const isRu = locale === 'ru';
  const seed = isRu ? POPULAR_AIRPORTS_RU : POPULAR_AIRPORTS;

  // 1. Измеренный спрос: сумма весов всех аэропортов страны, попавших в замер.
  const measured = new Map<string, number>();
  seed.forEach((iata, i) => {
    const country = getAirport(iata)?.country;
    if (!country) return;
    measured.set(country, (measured.get(country) ?? 0) + (RANK_WEIGHT[i] ?? 1));
  });

  /* 2. Хвост за пределами шестнадцати строк — по числу закреплённых по спросу
        аэропортов (lib/warm.ts). Это второй и последний измеренный источник в
        репозитории: два независимых замера, показы Вебмастера и визиты Метрики.
        Благодаря ему в каталог попадают Грузия, Таджикистан и Киргизия, которые иначе
        проигрывают Канаде и Бразилии по числу полос.

        ТОЛЬКО как разделитель внутри хвоста, НЕ как величина спроса. Закрепление
        ставится по правилу «в топе по спросу И ярусный норматив хуже шести часов», и
        второе условие выбрасывает самые крупные аэропорты: IST, DXB и PVG не закреплены
        именно потому, что они mega и свежесть получают и так. Сложить закрепления с
        измеренными весами значило бы штрафовать страну за крупный хаб.

        И только для русской локали: счётчик Метрики стоит на ней одной
        (components/YandexMetrica.tsx), так что к английской или японской главной этот
        список отношения не имеет. */
  const pinned = new Map<string, number>();
  if (isRu) {
    for (const iata of DEMAND_PINNED) {
      const country = getAirport(iata)?.country;
      if (country) pinned.set(country, (pinned.get(country) ?? 0) + 1);
    }
  }

  /* 3. Дальше — число аэропортов: про эти страны спроса не измерено вовсе, и размер
        единственное, что про них известно. Имя последним ключом нужно для
        устойчивости: у сотни стран по одному аэропорту, и без него порядок решала бы
        позиция строки в JSON. */
  return [...getCountries()].sort((x, y) =>
    (measured.get(y.country) ?? 0) - (measured.get(x.country) ?? 0)
    || (pinned.get(y.country) ?? 0) - (pinned.get(x.country) ?? 0)
    || y.count - x.count
    || x.country.localeCompare(y.country));
}
